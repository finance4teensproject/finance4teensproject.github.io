// Find which page the student is currently viewing
const path = window.location.pathname.split("/").pop();

const quizData = quizzes[path];


// Only run if this page has a quiz
if (quizData) {

    const form = document.getElementById("quiz-form");
    const total = document.getElementById("total");

    if (!form) {
        console.error("Quiz form not found.");
    } else {

        total.textContent = quizData.length;


        // Create the questions
        quizData.forEach((q, i) => {

            const div = document.getElementById(`question-${i}`);

            if (!div) {
                console.error(`question-${i} not found.`);
                return;
            }

            div.innerHTML = `<p><strong>${i + 1}. ${q.question}</strong></p>`;


            q.choices.forEach((choice, choiceIndex) => {

                const id = `q${i}_${choiceIndex}`;

                div.innerHTML += `
                    <label for="${id}">
                        <input
                            type="radio"
                            name="q${i}"
                            value="${choice}"
                            id="${id}"
                        >
                        ${choice}
                    </label>
                    <br>
                `;

            });

        });


        // Check answers when the student submits
        form.addEventListener("submit", function(event) {

            event.preventDefault();

            let score = 0;


            quizData.forEach((q, i) => {

                const selected = document.querySelector(
                    `input[name="q${i}"]:checked`
                );

                if (selected && selected.value === q.answer) {
                    score++;
                }

            });


            document.getElementById("quiz-results").style.display = "block";

            document.getElementById("score").textContent = score;

        });

    }
}
